namespace CardBot2.Domain;

/// <summary>
/// Возможные состояния пользователя в рамках диалога с ботом.
/// 
/// Состояние отражает:
/// - в каком режиме сейчас пользователь
/// - какую логику ожидать дальше
/// 
/// НЕ содержит бизнес-логики.
/// </summary>
public enum UserState
{
    /// <summary>
    /// Начальное состояние (по умолчанию).
    /// </summary>
    None,

    /// <summary>
    /// Пользователь находится в главном меню.
    /// </summary>
    MainMenu,

    /// <summary>
    /// Пользователь только что вытянул карту.
    /// </summary>
    ViewingCard
}